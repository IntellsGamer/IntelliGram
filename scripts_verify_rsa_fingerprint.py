from __future__ import annotations

import hashlib


def tl_bytes(value: bytes) -> bytes:
    if len(value) < 254:
        encoded = bytes([len(value)]) + value
    else:
        encoded = b"\xfe" + len(value).to_bytes(3, "little") + value
    return encoded + b"\x00" * (-len(encoded) % 4)


